"""Typed access to a running Claude Code (cc): profiles, active sessions, transcripts and cross-session messaging.

Unofficial and not affiliated with or endorsed by Anthropic. The package relies on undocumented Claude Code internals
that can change in any Claude Code release.

Everything importable from this package is the public API. Submodules are implementation details.

The names are imported on first use, so that importing a light submodule such as ``cc_blackbox.hooks`` does not load
the whole library. Type checkers see them through the ``TYPE_CHECKING`` imports below.
"""

